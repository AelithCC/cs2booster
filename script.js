function setLanguage(language) {
  currentLanguage = translations[language] || language === "de" ? language : "de";
  document.documentElement.lang = currentLanguage;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    element.innerHTML = currentLanguage === "de"
      ? element.dataset.originalHtml
      : translations[currentLanguage]?.[key] ?? element.dataset.originalHtml;
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    element.setAttribute(
      "placeholder",
      currentLanguage === "de"
        ? element.dataset.originalPlaceholder
        : translations[currentLanguage]?.[key] ?? element.dataset.originalPlaceholder
    );
  });

  document.querySelectorAll("[data-lang]").forEach((button) => {
    const active = button.dataset.lang === currentLanguage;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  document.title = dynamicText[currentLanguage].pageTitle;
  descriptionMeta?.setAttribute("content", dynamicText[currentLanguage].pageDescription);
  menu?.setAttribute("aria-label", nav?.classList.contains("open") ? dynamicText[currentLanguage].menuClose : dynamicText[currentLanguage].menuOpen);

  try {
    localStorage.setItem("aelith-language", currentLanguage);
  } catch {}

  calculateElo();
  filterCommands();
}


const eloForm = document.querySelector("#elo-form");
const currentEloInput = document.querySelector("#current-elo");
const targetEloInput = document.querySelector("#target-elo");
const eloError = document.querySelector("#elo-error");
const estimateRoute = document.querySelector("#estimate-route");
const eloDifference = document.querySelector("#elo-difference");
const eloPrice = document.querySelector("#elo-price");

const eloRates = [
  { end: 10000, rate: 2.49 },
  { end: 15000, rate: 3.49 },
  { end: 20000, rate: 4.99 },
  { end: 25000, rate: 6.49 },
  { end: 40000, rate: 8.49 }
];

function getBoostPrice(start, target) {
  let cursor = start;
  let price = 0;

  for (const tier of eloRates) {
    if (cursor >= target) break;
    if (cursor >= tier.end) continue;

    const tierEnd = Math.min(target, tier.end);
    const tierStart = Math.max(cursor, 0);
    if (tierEnd > tierStart) {
      price += ((tierEnd - tierStart) / 1000) * tier.rate;
      cursor = tierEnd;
    }
  }

  return Math.max(price, 9.99);
}

function formatNumber(value) {
  return new Intl.NumberFormat(localeByLanguage[currentLanguage]).format(value);
}

function formatPrice(value) {
  return new Intl.NumberFormat(localeByLanguage[currentLanguage], {
    style: "currency",
    currency: "EUR"
  }).format(value);
}

function calculateElo(event) {
  event?.preventDefault();
  if (!currentEloInput || !targetEloInput) return;

  const start = Number(currentEloInput.value);
  const target = Number(targetEloInput.value);
  const valuesValid = Number.isFinite(start) && Number.isFinite(target) && start >= 0 && target <= 40000;

  if (!valuesValid) {
    eloError.textContent = dynamicText[currentLanguage].eloInvalid;
    return;
  }

  if (target <= start) {
    eloError.textContent = dynamicText[currentLanguage].targetInvalid;
    return;
  }

  eloError.textContent = "";
  estimateRoute.textContent = `${formatNumber(start)} → ${formatNumber(target)} ELO`;
  eloDifference.textContent = `+${formatNumber(target - start)}`;
  eloPrice.textContent = formatPrice(getBoostPrice(start, target));
}

eloForm?.addEventListener("submit", calculateElo);
[currentEloInput, targetEloInput].forEach((input) => input?.addEventListener("input", () => {
  if (eloError.textContent) eloError.textContent = "";
}));

